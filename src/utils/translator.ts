// Deep translations on generic objects recursively
export function translateObject<T>(obj: T, targetLang: string): T {
  const code = getLangCode(targetLang);
  if (code === 'en' || !obj) return obj;

  if (typeof obj === 'string') {
    return translateText(obj, targetLang) as unknown as T;
  }

  if (Array.isArray(obj)) {
    return obj.map(item => translateObject(item, targetLang)) as unknown as T;
  }

  if (typeof obj === 'object') {
    const newObj = {} as any;
    for (const key of Object.keys(obj)) {
      const val = (obj as any)[key];
      // Do not translate technical identifiers, IDs, platforms, standard scores or formats
      if (
        key === 'id' || 
        key === 'platform' || 
        key === 'duration' || 
        key === 'timestamp' || 
        key === 'time' || 
        key === 'status' ||
        key === 'savedAt' ||
        key === 'avgViews' ||
        key === 'difficulty' && typeof val === 'string' && (val === 'Easy' || val === 'Medium' || val === 'Hard')
      ) {
        newObj[key] = val;
      } else {
        newObj[key] = translateObject(val, targetLang);
      }
    }
    return newObj as T;
  }

  return obj;
}

