// Helper to determine the target language code from various inputs
export function getLangCode(lang: string | undefined): string {
  if (!lang) return 'en';
  const clean = lang.trim().toLowerCase();
  const found = LANGUAGES.find(l => 
    l.code.toLowerCase() === clean || 
    l.name.toLowerCase() === clean ||
    (clean === 'spanish' && l.code === 'es') ||
    (clean === 'portuguese' && l.code === 'pt') ||
    (clean === 'german' && l.code === 'de') ||
    (clean === 'french' && l.code === 'fr') ||
    (clean === 'italian' && l.code === 'it') ||
    (clean === 'polish' && l.code === 'pl') ||
    (clean === 'ukrainian' && l.code === 'uk') ||
    (clean === 'norwegian' && l.code === 'no') ||
    (clean === 'arabic' && l.code === 'ar') ||
    (clean === 'hindi' && l.code === 'hi') ||
    (clean === 'japanese' && l.code === 'ja') ||
    (clean === 'korean' && l.code === 'ko')
  );
  return found ? found.code : 'en';
}

