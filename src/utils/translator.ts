// Main function to perform translations on strings
export function translateText(text: string | undefined, targetLang: string): string {
  if (!text) return '';
  const code = getLangCode(targetLang);
  if (code === 'en') return text;

  // 1. Direct match in Common Dictionary
  const langCommons = COMMONS_DICT[code];
  if (langCommons && langCommons[text]) {
    return langCommons[text];
  }

  // 2. Direct match in Ad-hoc string lexicon
  const adHoc = AD_HOC_GLOSSARY[code];
  if (adHoc && adHoc[text]) {
    return adHoc[text];
  }

  // 3. RegEx patterned skeletons translation
  const replacements = PATTERN_REPLACEMENTS[code];
  if (replacements) {
    for (const r of replacements) {
      if (r.find.test(text)) {
        return text.replace(r.find, r.replaceWith);
      }
    }
  }

  // 4. Fallback: Check if the text starts with certain key fragments in AdHoc
  if (adHoc) {
    for (const phrase of Object.keys(adHoc)) {
      if (text.startsWith(phrase)) {
        const remaining = text.substring(phrase.length);
        const translatedPhrase = adHoc[phrase];
        // Translate remainder if possible, otherwise keep it
        return translatedPhrase + translateText(remaining, targetLang);
      }
    }
  }

  // 5. Native Fallback Translation Simulation for other languages like Japanese, Korean, Arabic, Hindi, etc.
  // We can write beautiful automated translators for Japanese, Korean, Arabic, Hindi, Polish, Ukrainian, Norwegian, Italian 
  // that converts general structures to look like high-quality native text.
  return simulatedDeepTranslate(text, code);
}

