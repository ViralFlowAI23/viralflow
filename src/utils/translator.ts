// Top level instant translation helper for static tags and generic labels
export function t(text: string | undefined, targetLang: string): string {
  if (!text) return '';
  const code = getLangCode(targetLang);
  if (code === 'en') return text;

  // 1. Direct match in SUPPLEMENTARY_DICT
  if (SUPPLEMENTARY_DICT[code]?.[text]) {
    return SUPPLEMENTARY_DICT[code][text];
  }

  // 2. Direct match in UI_DICT
  if (UI_DICT[code]?.[text]) {
    return UI_DICT[code][text];
  }

  // 3. Direct match in COMMONS_DICT
  if (COMMONS_DICT[code]?.[text]) {
    return COMMONS_DICT[code][text];
  }

  // 4. Fallback to normal deep translate
  return translateText(text, targetLang);
}



